      <h1 class="text-3xl font-bold tracking-tight sm:text-4xl">Privacy Policy</h1>
      <p class="text-sm text-slate-400">Effective August 31, 2026</p>
    </header>

    <p>
      Colosseum is a match-planning whiteboard for FRC Team 4143 (MARS/WARS). This policy explains
      the information the app handles and the choices available to you.
    </p>

    <section class="space-y-3">
      <h2 class="text-xl font-semibold">Data stored on your device</h2>
      <p>
        Your matches, drawings, notes, team number, preferences, and any optional The Blue Alliance API key are
        stored locally on your device so the app can work without an account. The app does not operate an account
        system and does not collect advertising identifiers, analytics, or location data.
      </p>
      <p>
        You can remove local app data using the app’s Clear All control or by deleting the app.
      </p>
    </section>

    <section class="space-y-3">
      <h2 class="text-xl font-semibold">Sharing matches</h2>
      <p>
        Matches are shared only when you explicitly export them — as a PNG, a PDF, or a QR code — and only to the
        destination you choose. Colosseum does not upload your matches to any server.
      </p>
    </section>

    <section class="space-y-3">
      <h2 class="text-xl font-semibold">Third-party services</h2>
      <p>
        At your request, the app retrieves competition data from The Blue Alliance and match statistics from
        Statbotics. The app can also retrieve public contributor profile information from GitHub. Those services
        receive the network request needed to provide their information and handle it under their own policies.
        An optional personal The Blue Alliance API key is sent only when you use it to make a request.
      </p>
    </section>

    <section class="space-y-3">
      <h2 class="text-xl font-semibold">Camera</h2>
      <p>
        Camera access is optional and is used only to scan QR codes for importing match data. Camera images are
        processed on your device and are not recorded or uploaded by Colosseum.
      </p>
    </section>

    <section class="space-y-3">
      <h2 class="text-xl font-semibold">Security and retention</h2>
      <p>
        The app uses HTTPS for the optional network requests described above. All match data remains on your
        device unless you choose to export it.
      </p>
    </section>

    <section class="space-y-3">
      <h2 class="text-xl font-semibold">Contact and changes</h2>
      <p>
        Questions about this policy can be raised with the Team 4143 software group or on the project’s
        <a class="text-sky-400 hover:text-sky-300" href="https://github.com/FRC-Team-4143/colosseum" target="_blank" rel="noopener noreferrer">GitHub repository</a>.
        This policy may be updated when the app changes; the revised version will be posted on this page.
      </p>
    </section>
